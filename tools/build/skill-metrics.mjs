import { writeFileSync, mkdirSync } from 'node:fs';
import { face } from '../lib/type.mjs';

// Per-character advance widths (in em) for the weights the card script uses.
// Shipping these lets the skill's generator wrap text accurately without
// pulling in a font library — it stays a zero-dependency script.
const CHARS = ' !"#$%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`'
  + 'abcdefghijklmnopqrstuvwxyz{|}~£€·—–’‘“”…àâäçéèêëîïôöùûüñáíóúü';
const WEIGHTS = [400, 500, 700, 800];

const out = { note: 'Advance widths in em. Generated by tools/build/skill-metrics.mjs.', weights: {} };
for (const w of WEIGHTS) {
  const f = face(w, 'brand'), upem = f.unitsPerEm, m = {};
  for (const ch of CHARS) {
    const g = f.charToGlyph(ch);
    if (g) m[ch] = +(g.advanceWidth / upem).toFixed(4);
  }
  out.weights[w] = { capHeight: 0.745, fallback: +(f.charToGlyph('n').advanceWidth / upem).toFixed(4), chars: m };
}
mkdirSync('../skill/human-first-ai-brand/assets', { recursive: true });
writeFileSync('../skill/human-first-ai-brand/assets/metrics.json', JSON.stringify(out));
console.log('skill metrics:', WEIGHTS.length, 'weights,', CHARS.length, 'characters');

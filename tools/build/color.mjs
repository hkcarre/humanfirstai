// ----------------------------------------------------------- palette.ase
{
  const entries = PALETTE.filter(p => !['white', 'black'].includes(p.key));
  const u16 = v => { const b = Buffer.alloc(2); b.writeUInt16BE(v); return b; };
  const f32 = v => { const b = Buffer.alloc(4); b.writeFloatBE(v); return b; };
  const blocks = entries.map(p => {
    const nm = `HFAI ${p.name}`;
    const name = Buffer.alloc((nm.length + 1) * 2);
    for (let i = 0; i < nm.length; i++) name.writeUInt16BE(nm.charCodeAt(i), i * 2);
    const body = Buffer.concat([
      u16(nm.length + 1), name, Buffer.from('RGB ', 'ascii'),
      ...hexToRgb(p.hex).map(v => f32(v / 255)), u16(2),
    ]);
    const head = Buffer.alloc(6);
    head.writeUInt16BE(0x0001, 0);
    head.writeUInt32BE(body.length, 2);
    return Buffer.concat([head, body]);
  });
  const hdr = Buffer.alloc(12);
  hdr.write('ASEF', 0, 'ascii');
  hdr.writeUInt16BE(1, 4); hdr.writeUInt16BE(0, 6); hdr.writeUInt32BE(blocks.length, 8);
  writeFileSync(`${ROOT}/palette.ase`, Buffer.concat([hdr, ...blocks]));
}


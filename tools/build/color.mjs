// --- derived functional colours, solved for WCAG rather than eyeballed -----
const hsl2hex = (h, s, l) => {
  s /= 100; l /= 100;
  const k = n => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = n => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return '#' + [f(0), f(8), f(4)].map(v => Math.round(v * 255).toString(16).padStart(2, '0')).join('').toUpperCase();
};
function solve(hue, sat, minRatio) {
  for (let l = 60; l >= 5; l -= 0.25) {
    const hex = hsl2hex(hue, sat, l);
    if (contrast(hex, C.cream) >= minRatio && contrast(hex, C.white) >= minRatio) return hex;
  }
}

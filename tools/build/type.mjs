import sharp from 'sharp';
import { renderPng } from '../lib/type.mjs';
import { mkdirSync, writeFileSync } from 'node:fs';
import { C, BRAND } from '../lib/brand.mjs';

const ROOT = '../brand/type';
mkdirSync(ROOT, { recursive: true });
const W = (f, s) => writeFileSync(`${ROOT}/${f}`, s);

// ---------------------------------------------------------------------------
//  Type scale — one ratio (1.26, a major third rounded to whole pixels),
//  applied consistently. v1 mixed 1.53 / 1.55 / 1.29 / 1.31 between steps,
//  which is why its headings never felt related to its body copy.
// ---------------------------------------------------------------------------
export const SCALE = [
  { name: 'Display', px: 54, min: 36, lh: 1.08, track: '-0.03em', weight: 800, font: 'brand',
    role: 'Posters, campaign headers, the one line on a slide',
    sample: 'The future belongs to all of us.',
    rules: 'Two lines maximum. Balance the wraps by hand. Never set in capitals.' },
  { name: 'Headline', px: 34, min: 27, lh: 1.20, track: '-0.02em', weight: 700, font: 'brand',
    role: 'Section titles, booklet covers, slide openers',
    sample: 'Make AI feel like an open door, not a locked lab.',
    rules: 'Deep Ink. Optical kerning on. Leave at least 32px of air above it.' },
  { name: 'Title', px: 27, min: 23, lh: 1.30, track: '-0.015em', weight: 600, font: 'brand',
    role: 'Card titles, question headings, workshop agenda items',
    sample: 'What will I actually learn on Saturday?',
    rules: 'Use sentence case. A title that needs a colon is usually two titles.' },
  { name: 'Subhead', px: 21, min: 19, lh: 1.45, track: '-0.01em', weight: 500, font: 'brand',
    role: 'Standfirsts, key takeaways, pull quotes',
    sample: 'Free workshops in your neighbourhood, taught in your language.',
    rules: 'One sentence. If it runs past two lines it belongs in body copy.' },
  { name: 'Body', px: 17, min: 17, lh: 1.65, track: '0', weight: 400, font: 'readable',
    role: 'Curriculum, handouts, articles, letters',
    sample: 'Artificial intelligence should be as ordinary and dependable as electricity. You do not need a computer science degree to use it to run a market stall, protect a crop from drought, or help a child with homework.',
    rules: 'Atkinson Hyperlegible. 60–70 characters a line. Never justify. Never below 17px on screen or 11pt in print.' },
  { name: 'Small', px: 15, min: 15, lh: 1.60, track: '0', weight: 400, font: 'readable',
    role: 'Form help text, footnotes, table cells',
    sample: 'Bring a friend. We provide the tablets, the notebooks and the tea.',
    rules: 'The smallest size any sentence may be set in.' },
  { name: 'Caption', px: 14, min: 14, lh: 1.45, track: '0.01em', weight: 600, font: 'brand',
    role: 'Photo credits, timestamps, table headers, chapter tags',
    sample: 'Kibera Community Centre · Nairobi Chapter · 14 March 2026',
    rules: 'Separate with middots. Never put it in a pill. Never go below 14px — v1 allowed 13px, which fails for low-vision readers.' },
];

W('type-scale.json', JSON.stringify({ brand: BRAND.name, version: BRAND.version, ratio: 1.26, base: 17, steps: SCALE }, null, 2));

// --------------------------------------------------------------- fonts.css
W('fonts.css', `/* ${BRAND.name} — self-hosted fonts.
   Copy brand/type/fonts/ next to this file. Licences are OFL; ship them with the fonts.
   The variable file covers every weight we use, so one request serves the whole scale. */

@font-face {
  font-family: 'Plus Jakarta Sans';
  src: url('fonts/PlusJakartaSans-Variable.ttf') format('truetype-variations');
  font-weight: 200 800;
  font-style: normal;
  font-display: swap;
}
@font-face {
  font-family: 'Atkinson Hyperlegible';
  src: url('fonts/AtkinsonHyperlegible-Regular.ttf') format('truetype');
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}
@font-face {
  font-family: 'Atkinson Hyperlegible';
  src: url('fonts/AtkinsonHyperlegible-Bold.ttf') format('truetype');
  font-weight: 700;
  font-style: normal;
  font-display: swap;
}
`);

W('fonts-cdn.css', `/* ${BRAND.name} — hosted fonts, for prototypes and quick decks.
   Prefer fonts.css in production: it is faster on a 3G connection and sets no third-party cookies.

   Noto Sans JP is included here. v1 referenced it in its Japanese specimen but never
   loaded it, so the sample silently fell back to a system font. */
@import url('https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@400;500;600;700;800&family=Atkinson+Hyperlegible:wght@400;700&family=Noto+Sans+Arabic:wght@400;600;700&family=Noto+Sans+Devanagari:wght@400;600;700&family=Noto+Sans+JP:wght@400;600;700&display=swap');
`);

// ---------------------------------------------------------------- type.css
W('type.css', `/* ${BRAND.name} — type scale v${BRAND.version}
   Generated by tools/build/type.mjs. Pair with brand/color/tokens.css. */
:root {
${SCALE.map(s => `  --hf-size-${s.name.toLowerCase()}: clamp(${s.min}px, ${(s.min / 16).toFixed(3)}rem + ${((s.px - s.min) / 7.68).toFixed(3)}vw, ${s.px}px);`).join('\n')}
  --hf-measure: 66ch;
}

${SCALE.map(s => `.hf-${s.name.toLowerCase()} {
  font-family: var(--hf-font-${s.font});
  font-size: var(--hf-size-${s.name.toLowerCase()});
  line-height: ${s.lh};
  letter-spacing: ${s.track};
  font-weight: ${s.weight};
}`).join('\n\n')}

/* Body copy never exceeds a comfortable measure and is never justified. */
.hf-body, .hf-small { max-width: var(--hf-measure); text-align: start; }

/* Right-to-left. The mark itself never mirrors — a door opens the same way everywhere. */
[dir="rtl"] { --hf-font-readable: 'Noto Sans Arabic', 'Atkinson Hyperlegible', sans-serif; }
[dir="rtl"] .hf-body { font-size: calc(var(--hf-size-body) * 1.1); line-height: 1.8; }
`);

// --------------------------------------------------------------- specimen
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const wrapText = (t, n) => {
  const out = []; let cur = '';
  for (const w of t.split(' ')) { if ((cur + ' ' + w).trim().length > n) { out.push(cur.trim()); cur = w; } else cur += ' ' + w; }
  if (cur.trim()) out.push(cur.trim());
  return out;
};
const PAD = 64, WID = 1500;
let y = PAD + 100, rows = '';
for (const s of SCALE) {
  const fam = s.font === 'brand' ? 'Plus Jakarta Sans' : 'Atkinson Hyperlegible';
  const lines = wrapText(s.sample, Math.max(26, Math.round(1180 / (s.px * 0.5))));
  rows += `  <text x="${PAD}" y="${y}" font-family="Plus Jakarta Sans" font-size="13" font-weight="700" fill="#C24D00" letter-spacing="1.2">${esc(s.name.toUpperCase())}</text>
  <text x="${PAD + 150}" y="${y}" font-family="Plus Jakarta Sans" font-size="13" fill="#68728A">${s.px}px / ${s.lh} / ${esc(s.track)} / ${s.weight} / ${fam}</text>\n`;
  y += 18;
  for (const [i, l] of lines.entries()) {
    y += s.px * s.lh;
    rows += `  <text x="${PAD}" y="${y}" font-family="${fam}" font-size="${s.px}" font-weight="${s.weight}" fill="${C.ink}">${esc(l)}</text>\n`;
    if (i > 2) break;
  }
  y += Math.max(24, Math.round(s.px * 0.42));
  rows += `  <text x="${PAD}" y="${y}" font-family="Plus Jakarta Sans" font-size="13" fill="#68728A">${esc(s.role)} — ${esc(s.rules)}</text>\n`;
  y += 44;
  rows += `  <line x1="${PAD}" y1="${y - 22}" x2="${WID - PAD}" y2="${y - 22}" stroke="#68728A" stroke-width="0.6" opacity="0.4"/>\n`;
}
const specimen = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WID} ${y + PAD}" width="${WID}" height="${y + PAD}">
  <rect width="${WID}" height="${y + PAD}" fill="${C.cream}"/>
  <text x="${PAD}" y="${PAD + 34}" font-family="Plus Jakarta Sans" font-size="34" font-weight="800" fill="${C.ink}">Human First AI — typography</text>
  <text x="${PAD}" y="${PAD + 64}" font-family="Plus Jakarta Sans" font-size="16" fill="#68728A">Plus Jakarta Sans carries the brand. Atkinson Hyperlegible carries anything anyone has to read for more than a sentence.</text>
${rows}</svg>`;
W('type-specimen.svg', specimen);
await renderPng(sharp, specimen, { width: 1900 }, `${ROOT}/type-specimen.png`);

console.log(`type: ${SCALE.length}-step scale, type.css, fonts.css, fonts-cdn.css, specimen`);
